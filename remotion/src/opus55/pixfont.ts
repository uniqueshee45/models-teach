export const glyph = (c: string) => (FONT[c] ?? FONT['?']).split('|');
export const adv = (c: string) => c === ' ' ? 3 : glyph(c)[0].length + 1;
export const tw = (s: string) => [...s].reduce((a, c) => a + adv(c), 0) - 1;
const TD = new Map<string, string>();
export const textD = (s: string) => {
  if (!TD.has(s)) {
    let x = 0, d = '';
    for (const c of s) {
      if (c !== ' ') glyph(c).forEach((row, y) => {for (let i = 0; i < row.length;) {if (row[i] !== '#') {i++; continue;} let e = i; while (row[e] === '#') e++; d += `M${x + i} ${y}h${e - i}v1h${i - e}z`; i = e;}});
      x += adv(c);
    }
    TD.set(s, d);
  }
  return TD.get(s)!;
};
